/* global __dirname */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const Module=require('node:module');
const path=require('node:path');
const file=path.resolve(__dirname,'../src/model.ts');
const result=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
const mod=new Module(file,module);mod._compile(result.outputText,file);
const {parseRoutines}=mod.exports;
const catalogFile=path.resolve(__dirname,'../src/catalog-utils.ts');
const catalogModule=new Module(catalogFile,module);
catalogModule._compile(ts.transpileModule(fs.readFileSync(catalogFile,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,catalogFile);
const {ALL_GROUPS,getGroupOptions,filterExercises}=catalogModule.exports;
const catalog=require('../src/catalog.json');
const ids=new Set(catalog.map(e=>e.id));
assert.equal(catalog.length,750);assert.equal(ids.size,catalog.length);
const options=getGroupOptions(catalog);
assert.equal(new Set(options.map(option=>option.id)).size,options.length,'Filter keys must be unique');
assert.equal(options.filter(option=>option.label==='Todos').length,1,'Only one all-exercises filter');
assert.equal(filterExercises(catalog,ALL_GROUPS,'').length,750,'All must include uncategorized exercises');
assert.equal(filterExercises(catalog,'Todos','').length,57,'Original Todos group must remain accessible');
assert.ok(options.some(option=>option.value==='Todos'&&option.label==='General'));
assert.deepEqual(filterExercises(catalog,ALL_GROUPS,'BICEPS'),filterExercises(catalog,ALL_GROUPS,'bíceps'));
assert.ok(filterExercises(catalog,ALL_GROUPS,'press mancuernas').every(exercise=>/press/i.test(exercise.name)&&/mancuernas/i.test(exercise.name)));
assert.equal(filterExercises(catalog,ALL_GROUPS,'zz-no-exercise-zz').length,0);
for(const e of catalog){assert.ok(e.name&&e.group);assert.match(e.url,/^https:\/\/fitcron\.com\/exercise\//);assert.match(e.gif,/^https:\/\/fitcron\.com\/wp-content\/uploads\/.+\.gif$/);}
const routine={id:'original',name:'Lunes · Pecho',entries:[{id:'entry',exerciseId:catalog[0].id,sets:'3',reps:'10–12',rest:'90',notes:'Técnica controlada'}]};
const serialized=JSON.stringify({version:1,routines:[routine]});
const parsed=parseRoutines(serialized,ids);
const hydrated=parseRoutines(serialized,ids,true);
assert.equal(hydrated[0].id,routine.id,'Hydration must preserve routine IDs for navigation');
assert.equal(hydrated[0].entries[0].id,'entry','Hydration must preserve session entry IDs');
assert.equal(parsed[0].name,routine.name);assert.equal(parsed[0].entries[0].notes,routine.entries[0].notes);
assert.notEqual(parsed[0].id,routine.id);assert.notEqual(parsed[0].entries[0].id,'entry');
assert.notEqual(parseRoutines(serialized,ids)[0].id,parsed[0].id);
for(const invalid of ['null','{}','not json',JSON.stringify({version:2,routines:[]}),JSON.stringify({version:1,routines:[{...routine,entries:[{...routine.entries[0],exerciseId:'missing'}]}]}),JSON.stringify({version:1,routines:[{...routine,name:''}]}),JSON.stringify({version:1,routines:[{...routine,entries:[{...routine.entries[0],sets:3}]}]})])assert.throws(()=>parseRoutines(invalid,ids));
console.log('OK: 750 ejercicios; filtros con claves únicas; Todos/General; búsqueda sin tildes; importación/exportación; IDs nuevos; rechazo de datos incompatibles.');

const workoutFile=path.resolve(__dirname,'../src/workout-model.ts');
const workoutModule=new Module(workoutFile,module);
workoutModule.require=id=>id==='./model'?mod.exports:require(id);
workoutModule._compile(ts.transpileModule(fs.readFileSync(workoutFile,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,workoutFile);
const {createWorkout,toggleSet,workoutProgress,nextPending,remainingSeconds,formatTime,restoreWorkout}=workoutModule.exports;
const plan={...routine,entries:[...routine.entries,{...routine.entries[0],id:'second',sets:'2'}, {...routine.entries[0],id:'third',sets:'1'}]};
const before=JSON.stringify(plan);
let workout=createWorkout(plan,1000);
assert.equal(workout.currentEntryId,'entry');
assert.deepEqual(workoutProgress(workout),{done:0,total:6});
workout=toggleSet(workout,'third',0);
assert.equal(workout.completed.entry[0],false,'Identical exercises must have independent set marks');
workout={...workout,currentEntryId:'third'};
assert.equal(nextPending(workout),'entry','Skipping ahead must wrap back to unfinished exercises');
workout=toggleSet(workout,'entry',0);
assert.deepEqual(workoutProgress(workout),{done:2,total:6});
workout=toggleSet(workout,'entry',0);
assert.deepEqual(workoutProgress(workout),{done:1,total:6},'Tapping again must undo a set');
assert.equal(toggleSet(workout,'entry',-1),workout);
assert.equal(toggleSet(workout,'entry',999),workout);
assert.equal(JSON.stringify(plan),before,'Training must not mutate the saved routine');
plan.entries[0].notes='Edited outside the workout';
assert.equal(workout.routine.entries[0].notes,'Técnica controlada','A running session must keep its snapshot');
const resumed=restoreWorkout(JSON.stringify(workout),ids,10000);
assert.equal(resumed.currentEntryId,'third');assert.deepEqual(resumed.completed,workout.completed);assert.equal(resumed.routine.id,workout.routine.id);
for(const entry of workout.routine.entries)for(let i=0;i<workout.completed[entry.id].length;i++)if(!workout.completed[entry.id][i])workout=toggleSet(workout,entry.id,i);
assert.equal(nextPending(workout),null);assert.deepEqual(workoutProgress(workout),{done:6,total:6});
const finished={...workout,finishedAt:10000};assert.equal(toggleSet(finished,'entry',0),finished);
assert.equal(remainingSeconds(91000,1000),90);assert.equal(remainingSeconds(91000,90500),1);assert.equal(remainingSeconds(91000,200000),0,'Timer must use wall-clock deadlines after background suspension');
assert.equal(formatTime(90),'1:30');assert.equal(formatTime(0),'0:00');
const expired={...resumed,rest:{id:'rest',entryId:'entry',endsAt:9000,seconds:8,notified:false}};
assert.equal(restoreWorkout(JSON.stringify(expired),ids,10000).rest.notified,true,'Restoring an old timer must not vibrate again');
for(const sets of ['','0','-1','2.5','NaN','101'])assert.throws(()=>createWorkout({...routine,entries:[{...routine.entries[0],sets}]}));
assert.throws(()=>createWorkout({...routine,entries:[]}));
assert.throws(()=>restoreWorkout(JSON.stringify({...resumed,completed:{entry:[true]}}),ids));
console.log('OK: sesión independiente; marcar/desmarcar; salto y retorno de pendientes; recuperación; temporizador por fecha; rechazo de series inválidas.');
const example=require('../src/examples/monday-chest-triceps.json');
const importedExample=parseRoutines(JSON.stringify(example),ids);
assert.equal(importedExample[0].name,'Lunes - Pecho y Tríceps');
assert.equal(importedExample[0].entries.length,5);
assert.deepEqual(workoutProgress(createWorkout(importedExample[0])),{done:0,total:12});
assert.ok(importedExample[0].entries.every(entry=>ids.has(entry.exerciseId)));
console.log('OK: ejemplo Lunes - Pecho y Tríceps importable; 5 ejercicios reales y 12 series.');
